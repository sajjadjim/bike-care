export function getModelsForManufacturer(type: VehicleType, manufacturer: string): string[] {
  if (manufacturer === 'Other') return ['Other'];
  if (type === 'motorcycle') {
    if (manufacturer === 'Honda') return VEHICLE_MODELS_PRESET['Honda (motorcycle)'] || ['Other'];
    if (manufacturer === 'Suzuki') return VEHICLE_MODELS_PRESET['Suzuki (motorcycle)'] || ['Other'];
    if (manufacturer === 'BMW') return VEHICLE_MODELS_PRESET['BMW (motorcycle)'] || ['Other'];
    return VEHICLE_MODELS_PRESET[manufacturer] || ['Standard', 'Other'];
  } else {
    if (manufacturer === 'Honda') return VEHICLE_MODELS_PRESET['Honda (car)'] || ['Other'];
    if (manufacturer === 'Suzuki') return VEHICLE_MODELS_PRESET['Suzuki (car)'] || ['Other'];
    if (manufacturer === 'BMW') return VEHICLE_MODELS_PRESET['BMW (car)'] || ['Other'];
    return VEHICLE_MODELS_PRESET[manufacturer] || ['Standard', 'Other'];
  }
}

